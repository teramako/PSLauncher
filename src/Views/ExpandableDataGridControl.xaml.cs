/// <summary>
/// ExpandableDataGridControl.xaml
/// </summary>
public partial class ExpandableDataGridControl : UserControl, IResultContentControl
{
    public ExpandableDataGridControl()
    {
        InitializeComponent();
    }

    private List<DataGridColumn>? ObjectDataGridColumns;
    private List<DataGridColumn>? FileDataGridColumns;

    private void OnDataContextChanged(object sender, DependencyPropertyChangedEventArgs e)
    {
        switch (e.NewValue)
        {
            case ResultList newList:
                Root.Visibility = newList is { Kind: ResultDataKind.Simple or ResultDataKind.NotSpecified }
                                ? Visibility.Collapsed
                                : Visibility.Visible;
                Root.AutoGenerateColumns = false;
                ChangeColumns(newList, e.OldValue as ResultList);
                SetContextMenu(newList);
                break;
            case TableList:
                Root.Visibility = Visibility.Visible;
                Root.AutoGenerateColumns = true;
                break;
        }
    }

    private void OnAutoGeneratingColumn(object sender, DataGridAutoGeneratingColumnEventArgs e)
    {
        if (DataContext is not TableList tableList)
            return;

        e.Column.SortMemberPath = e.PropertyName;
        var dataType = tableList.DataType;
        if (PSObjectsMembers.TryGetColumns(dataType, out var columnDict))
        {
            if (columnDict.TryGetValue(e.PropertyName, out var column))
            {
                if (!column.Enalbed)
                {
                    e.Cancel = true;
                }
            }
        }
    }

    private void OnAutoGeneratedColumns(object sender, EventArgs e)
    {
        if (DataContext is not TableList tableList)
            return;

        var dataType = tableList.DataType;
        if (!PSObjectsMembers.TryGetColumns(dataType, out var columnDict))
            return;

        foreach (var column in Root.Columns)
        {
            if (column.Header is not string header
                || !columnDict.TryGetValue(header, out var gridColumn))
            {
                column.Visibility = Visibility.Collapsed;
                continue;
            }

            if (header != gridColumn.Header)
                column.Header = gridColumn.Header;

            if (gridColumn.DisplayIndex >= 0)
                column.DisplayIndex = gridColumn.DisplayIndex;

            column.Visibility = gridColumn.Visible ? Visibility.Visible : Visibility.Collapsed;
        }
    }

    private void ChangeColumns(ResultList? newList, ResultList? oldList)
    {
        if (newList is null)
            return;
        if (oldList is not null && oldList.Kind == newList.Kind)
            return;

        List<DataGridColumn> columns;
        switch (newList.Kind)
        {
            case ResultDataKind.Objects:
                columns = ObjectDataGridColumns ??=
                [
                    (DataGridTemplateColumn)Resources["NameColumn"],
                    (DataGridTemplateColumn)Resources["ValueColumn"],
                    (DataGridTextColumn)Resources["TypeColumn"]
                ];
                break;
            case ResultDataKind.Files:
                columns = FileDataGridColumns ??=
                [
                    (DataGridTemplateColumn)Resources["FileNameColumn"],
                    (DataGridTextColumn)Resources["FileLastModifiedColumn"],
                    (DataGridTextColumn)Resources["FileSizeColumn"]
                ];
                break;
            default:
                return;
        }
        Root.Columns.Clear();
        columns.ForEach(Root.Columns.Add);
    }
    private void SetContextMenu(ResultList? dataList)
    {
        if (dataList is null)
            return;
        switch (dataList.Kind)
        {
            case ResultDataKind.Objects:
                Root.ContextMenu = TryFindResource("ObjectsContextMenu") as ContextMenu;
                break;
            case ResultDataKind.Files:
                Root.ContextMenu = TryFindResource("FilesContextMenu") as ContextMenu;
                break;
            default:
                Root.ContextMenu = null;
                break;
        }
    }

    private void OnGotFocus(object sender, RoutedEventArgs e)
    {
        if (e.OriginalSource is DataGrid dataGrid)
        {
            FocusToResultGrid(dataGrid, -1);
        }
    }

    public void FocusToContent()
    {
        Dispatcher.BeginInvoke(() =>
        {
            FocusToResultGrid(Root, -1);
        }, DispatcherPriority.Background);
    }

    private static void FocusToResultGrid(DataGrid dataGrid, int rowIndex = 0)
    {
        if (dataGrid.Items.Count == 0)
            return;
        if (rowIndex < 0)
            rowIndex = dataGrid.SelectedIndex;
        var index = Math.Clamp(rowIndex, 0, dataGrid.Items.Count - 1);
        dataGrid.SelectedIndex = index;
        dataGrid.UpdateLayout();
        if (dataGrid.ItemContainerGenerator.ContainerFromIndex(index) is not DataGridRow row)
            return;
        row.MoveFocus(new(FocusNavigationDirection.Next));
    }

    private void OnRowPreviewKeyDown(object sender, KeyEventArgs e)
    {
        if (!WpfUtils.TryFindParent<DataGrid>(sender as DependencyObject, out var dataGrid))
            return;

        var data = DataContext as ResultList;
        if (data is null)
            return;
        var selectedIndex = dataGrid.SelectedIndex;
        if (selectedIndex < 0) return;
        switch (e.Key)
        {
            case Key.Enter:
                e.Handled = data.Toggle(selectedIndex);
                break;
            case Key.Right:
                data.Expand(selectedIndex);
                e.Handled = true;
                break;
            case Key.Left:
                var parentIndex = data.Collapse(selectedIndex);
                FocusToResultGrid(dataGrid, parentIndex);
                e.Handled = true;
                break;
            case Key.P when Keyboard.Modifiers is ModifierKeys.Control:
                Commands.PinItem.Execute(dataGrid.SelectedItems, dataGrid);
                e.Handled = true;
                break;
            default:
                return;
        }

    }

    private void OnToggleRowExpander(object sender, RoutedEventArgs e)
    {
        if (!WpfUtils.TryFindParent<DataGrid>(sender as DependencyObject, out var dataGrid))
            return;

        var selectedIndex = dataGrid.SelectedIndex;
        e.Handled = (DataContext as ResultList)?.Toggle(selectedIndex) ?? false;
    }

    private void OnSorting(object sender, DataGridSortingEventArgs e)
    {
        if (DataContext is not ResultList dataList)
            return;
        var col = e.Column;
        var currentDirection = col.SortDirection;
        ListSortDirection? sortDirection = currentDirection switch
        {
            ListSortDirection.Ascending => ListSortDirection.Descending,
            ListSortDirection.Descending => null,
            _ => ListSortDirection.Ascending,
        };
        if (dataList.Sort(sortDirection, col.SortMemberPath))
        {
            col.SortDirection = sortDirection;
            e.Handled = true;
        }
    }

    private void OnCanCopyValue(object sender, CanExecuteRoutedEventArgs e)
    {
        e.CanExecute = Root.SelectedItems.OfType<object?>().Any(x => x switch
        {
            null => false,
            IResultData item => item.ValueType switch
            {
                ObjectValueType.Null => false,
                ObjectValueType.String or ObjectValueType.Number or ObjectValueType.Boolean
                or ObjectValueType.Enum or ObjectValueType.Temporal or ObjectValueType.Exception
                or ObjectValueType.File or ObjectValueType.Directory => true,
                _ => !string.IsNullOrEmpty(Utils.ObjectToString(item.RawValue))
            },
            _ => true
        });
        e.Handled = true;
    }

    private void OnCopyValue(object sender, ExecutedRoutedEventArgs e)
    {
        StringCollection files = [];
        List<string> texts = [];
        foreach (var obj in Root.SelectedItems)
        {
            e.Handled = true;
            switch (obj)
            {
                case IResultData item:
                    switch (item.ValueType)
                    {
                        case ObjectValueType.File or ObjectValueType.Directory:
                            AddAsFileSystem(item.RawValue);
                            break;
                        case ObjectValueType.String or ObjectValueType.Number:
                        case ObjectValueType.Boolean or ObjectValueType.Enum:
                        case ObjectValueType.Temporal or ObjectValueType.Exception:
                            texts.Add($"{item.RawValue}");
                            break;
                        default:
                            AddAsText(item.RawValue);
                            break;
                    }
                    break;
                case ValueData valueData:
                    if (valueData.Value is FileSystemInfo)
                        AddAsFileSystem(valueData.Value);
                    else
                        AddAsText(valueData.Value);
                    break;
                case FileSystemInfo fileSystemInfo:
                    AddAsFileSystem(fileSystemInfo);
                    break;
                default:
                    AddAsText(obj);
                    break;
            }
        }
        var data = new DataObject();
        if (files.Count > 0)
            data.SetFileDropList(files);
        if (texts.Count > 0)
            data.SetText(string.Join(Environment.NewLine, texts));
        Clipboard.SetDataObject(data, true);

        void AddAsFileSystem(object? fileSystemInfo)
        {
            if (fileSystemInfo is null)
                return;
            var filePath = $"{fileSystemInfo}";
            files.Add(filePath);
            texts.Add(filePath);
        }
        void AddAsText(object? obj)
        {
            var text = Utils.ObjectToString(obj);
            texts.Add(text);
        }
    }
    private void OnCanCopyRow(object sender, CanExecuteRoutedEventArgs e)
    {
        e.CanExecute = Root.SelectedItems.Count > 0;
        e.Handled = true;
    }

    private void OnCopyRow(object sender, ExecutedRoutedEventArgs e)
    {
        var items = Root.SelectedItems;
        var columns = Root.Columns.Where(col => col.Visibility == Visibility.Visible)
                                  .OrderBy(col => col.DisplayIndex)
                                  .ToArray();
        List<string> lines = [];
        foreach (var item in items)
        {
            var line = item is IResultData data
                ? string.Join("\t", columns.Select(col => data.GetColumnValue(col.SortMemberPath)))
                : string.Join("\t", columns.Select(col => $"{item.GetType().GetProperty(col.SortMemberPath)?.GetValue(item)}"));
            lines.Add(line);
        }

        var text = string.Join(Environment.NewLine, lines);
        if (!string.IsNullOrEmpty(text))
        {
            Clipboard.SetText(text);
            e.Handled = true;
        }
    }

    #region OpenInObjectsTreeWindow command handlers
    private void OnCanOpenInObjectsTreeWindow(object sender, CanExecuteRoutedEventArgs e)
    {
        var items = Root.SelectedItems;
        if (items.Count == 0)
        {
            e.CanExecute = false;
            return;
        }

        if (items.Count == 1)
        {
            e.CanExecute = items[0] is IResultData data && data switch
            {
                { RawValue: null } => false,
                { ValueType: ObjectValueType.Null } => false,
                { ValueType: ObjectValueType.Boolean } => false,
                { ValueType: ObjectValueType.Number } => false,
                { ValueType: ObjectValueType.Enum } => false,
                { ValueType: ObjectValueType.String } => false,
                _ => true
            };
        }
        else
        {
            e.CanExecute = !items.OfType<IResultData>().All(static x => x.NodeType is ObjectNodeType.VirtualRow);
        }
    }
    private void OnOpenInObjectsTreeWindow(object sender, ExecutedRoutedEventArgs e)
    {
        IResultList resultList;
        var items = Root.SelectedItems;
        if (items.Count == 0)
            return;
        if (items.Count == 1)
        {
            if (items[0] is not IResultData data || data.RawValue is null || data.ValueType is ObjectValueType.Null)
                return;

            resultList = ResultList.Build(data.RawValue, ResultDataKind.Objects);
        }
        else
        {
            var list = items.OfType<IResultData>()
                            .Where(static x => x.ValueType is not ObjectValueType.Null)
                            .Select(static x => x.RawValue)
                            .ToArray();
            if (list.Length == 0)
                return;
            resultList = ResultList.Build(list, ResultDataKind.Objects);
        }

        var win = new ObjectsViewWindow(resultList);
        win.Show();
    }
    #endregion

    #region OpenInFilesTreeWindow command handlers
    private void OnCanOpenInFilesTreeWindow(object sender, CanExecuteRoutedEventArgs e)
    {
        var items = Root.SelectedItems;
        e.CanExecute = items.OfType<IResultData>()
                            .Any(static x => x.RawValue is FileSystemInfo);
    }
    private void OnOpenInFilesTreeWindow(object sender, ExecutedRoutedEventArgs e)
    {
        var items = Root.SelectedItems;
        var fileInfos = items.OfType<IResultData>()
                             .Select(x => x.RawValue)
                             .OfType<FileSystemInfo>()
                             .ToArray();
        var resultList = ResultList.BuildAsFilesTree(fileInfos);
        var win = new ObjectsViewWindow(resultList);
        win.Show();
    }
    #endregion

    #region OpenInTableViewWindow command handlers
    private void OnCanOpenInTableViewWindow(object sender, CanExecuteRoutedEventArgs e)
    {
        var items = Root.SelectedItems;
        e.CanExecute = items.OfType<IResultData>().Any(static x => x.RawValue is not null);
    }
    private void OnOpenInTableViewWindow(object sender, ExecutedRoutedEventArgs e)
    {
        TableList tableList;
        var items = Root.SelectedItems;
        if (items.Count == 1)
        {
            if (items[0] is not IResultData item || item.RawValue is null)
                return;

            tableList = item.RawValue is IEnumerable enumerable
                ? TableList.Build(enumerable)
                : TableList.Build(item.RawValue);
        }
        else
        {
            var resultsData = items.OfType<IResultData>().Where(static x => x.RawValue is not null);
            tableList = TableList.Build(resultsData.Select(x => x.RawValue));
        }

        var win = new ObjectsViewWindow(tableList);
        win.Show();
    }
    #endregion
}
